class RFMAnalyzer:
    """
    Level 1: RFM Analysis
    
    Scores customers 1-5 on Recency, Frequency, Monetary.
    Identifies high-value at-risk customers.
    """
    
    def __init__(self, churn_threshold: int = 183):
        self.churn_threshold = churn_threshold
        self.rfm_df = None
        
    def calculate_rfm(self, df: pd.DataFrame, 
                      date_col: str = None,
                      id_col: str = None, 
                      point_col: str = None,
                      qty_col: str = None) -> pd.DataFrame:
        """Calculate RFM scores for all customers."""
        
        # Auto-detect columns
        if date_col is None:
            date_col = self._find_col(df, ['trxn_date', 'date', 'trxn'])
        if id_col is None:
            id_col = self._find_col(df, ['membership', 'loyalty', 'id', 'customer'])
        if point_col is None:
            point_col = self._find_col(df, ['point_awarded', 'point', 'points'])
        if qty_col is None:
            qty_col = self._find_col(df, ['quantity', 'qty'])
            
        if not date_col or not id_col:
            raise ValueError("Could not find required date/id columns")
        
        df = df.copy()
        df[date_col] = pd.to_datetime(df[date_col])
        
        # Store original id column name
        self.id_col = id_col
        
        analysis_date = df[date_col].max()
        
        # Aggregate per customer
        agg_dict = {
            date_col: ['max', 'count'],
        }
        if point_col and point_col in df.columns:
            agg_dict[point_col] = 'sum'
        if qty_col and qty_col in df.columns:
            agg_dict[qty_col] = 'sum'
            
        rfm = df.groupby(id_col).agg(agg_dict).reset_index()
        
        # Flatten columns
        rfm.columns = ['customer_id', 'last_purchase', 'frequency', 
                       'monetary' if point_col else 'temp1',
                       'total_qty' if qty_col else 'temp2']
        
        # Remove temp columns if created
        rfm = rfm[[c for c in rfm.columns if not c.startswith('temp')]]
        
        # Calculate Recency
        rfm['recency_days'] = (analysis_date - rfm['last_purchase']).dt.days
        
        # Calculate inter-purchase time
        purchase_times = df.groupby(id_col)[date_col].apply(
            lambda x: x.sort_values().diff().dt.days.mean()
        ).reset_index()
        purchase_times.columns = ['customer_id', 'avg_purchase_gap']
        rfm = rfm.merge(purchase_times, on='customer_id', how='left')
        
        # Score 1-5 (1=best for recency, 5=best for frequency/monetary)
        rfm['R_score'] = pd.qcut(rfm['recency_days'], 5, labels=[5,4,3,2,1], duplicates='drop').astype(int)
        rfm['F_score'] = pd.qcut(rfm['frequency'].rank(method='first'), 5, labels=[1,2,3,4,5], duplicates='drop').astype(int)
        
        if 'monetary' in rfm.columns:
            rfm['M_score'] = pd.qcut(rfm['monetary'].rank(method='first'), 5, labels=[1,2,3,4,5], duplicates='drop').astype(int)
        else:
            rfm['M_score'] = 3  # Default mid-score
            
        # Combined RFM score
        rfm['RFM_score'] = rfm['R_score'] + rfm['F_score'] + rfm['M_score']
        
        # Churn flags (FIRST - before segmentation)
        rfm['is_churned'] = rfm['recency_days'] >= self.churn_threshold  # 183+ days
        rfm['recently_churned'] = (rfm['recency_days'] >= 183) & (rfm['recency_days'] <= 365)
        rfm['long_term_churned'] = rfm['recency_days'] > 365
        
        # Churn timeline category
        def get_churn_timeline(days):
            if days < 183:
                return 'ACTIVE'
            elif days <= 365:
                return 'CHURNED_OUT_RECENTLY'  # 183-365 days
            else:
                return 'CHURNED_OUT_LONG_TERM'  # 365+ days
        
        rfm['churn_timeline'] = rfm['recency_days'].apply(get_churn_timeline)
        
        # Risk segments (for ACTIVE customers only, based on RFM)
        def get_segment(row):
            r, f, m = row['R_score'], row['F_score'], row['M_score']
            days = row['recency_days']
            
            # If already churned (183+ days), categorize by churn timeline
            if days >= 365:
                return 'CHURNED_OUT_LONG_TERM'
            elif days >= 183:
                return 'CHURNED_OUT_RECENTLY'
            
            # For active customers (< 183 days), use RFM segments
            # HIGHEST PRIORITY: Was loyal, now drifting (high F, low R but still active)
            if f >= 4 and r <= 2:
                return 'AT_RISK_HIGH_VALUE'  # High frequency but low recency = drifting
            elif r == 5 and f >= 4:
                return 'LOYAL_ACTIVE'  # Recent + Frequent = best customers
            elif r >= 4 and f >= 3:
                return 'ACTIVE'
            elif f >= 4 and r <= 3:
                return 'AT_RISK'  # High F but not recent
            elif r <= 2 and f <= 2:
                return 'DORMANT'  # Not recent, not frequent
            elif f <= 2:
                return 'NEW_OR_OCCASIONAL'
            else:
                return 'MODERATE'
                
        rfm['segment'] = rfm.apply(get_segment, axis=1)
        
        # Priority ranking
        priority_map = {
            'AT_RISK_HIGH_VALUE': 1,  # HIGHEST - was good, now drifting (still active)
            'AT_RISK': 2,
            'CHURNED_OUT_RECENTLY': 3,  # Recently churned - win-back opportunity
            'DORMANT': 4,
            'MODERATE': 5,
            'ACTIVE': 6,
            'NEW_OR_OCCASIONAL': 7,
            'CHURNED_OUT_LONG_TERM': 8,  # Long-term churned - low priority
            'LOYAL_ACTIVE': 9  # LOWEST priority (already doing well)
        }
        rfm['action_priority'] = rfm['segment'].map(priority_map)
        
        self.rfm_df = rfm.sort_values('action_priority')
        return self.rfm_df
    
    def get_at_risk_high_value(self) -> pd.DataFrame:
        """Get high-value at-risk customers (was loyal, now drifting)."""
        if self.rfm_df is None:
            raise ValueError("Run calculate_rfm first")
        return self.rfm_df[self.rfm_df['segment'] == 'AT_RISK_HIGH_VALUE']
    
    def get_churning_champions(self) -> pd.DataFrame:
        """Alias for get_at_risk_high_value for backwards compatibility."""
        return self.get_at_risk_high_value()
    
    def get_at_risk(self) -> pd.DataFrame:
        """Get all at-risk customers (still active but showing risk signs)."""
        if self.rfm_df is None:
            raise ValueError("Run calculate_rfm first")
        return self.rfm_df[self.rfm_df['segment'].isin(['AT_RISK_HIGH_VALUE', 'AT_RISK'])]
    
    def get_recently_churned(self) -> pd.DataFrame:
        """Get recently churned customers (183-365 days inactive)."""
        if self.rfm_df is None:
            raise ValueError("Run calculate_rfm first")
        return self.rfm_df[self.rfm_df['segment'] == 'CHURNED_OUT_RECENTLY'].copy()
    
    def get_churned_out(self) -> pd.DataFrame:
        """Get all churned out customers (183+ days inactive)."""
        if self.rfm_df is None:
            raise ValueError("Run calculate_rfm first")
        return self.rfm_df[self.rfm_df['is_churned'] == True].copy()

    
    def get_churn_timeline_summary(self) -> pd.DataFrame:
        """Get summary of customers by churn timeline."""
        if self.rfm_df is None:
            raise ValueError("Run calculate_rfm first")
        
        summary = self.rfm_df.groupby('churn_timeline').agg({
            'customer_id': 'count',
            'recency_days': ['mean', 'min', 'max'],
            'frequency': 'mean',
            'RFM_score': 'mean'
        }).round(1)
        
        summary.columns = ['count', 'avg_recency', 'min_recency', 'max_recency', 'avg_frequency', 'avg_rfm_score']
        return summary.reset_index()
    
    def _find_col(self, df: pd.DataFrame, keywords: List[str]) -> Optional[str]:
        """Find column matching keywords."""
        for col in df.columns:
            for kw in keywords:
                if kw.lower() in col.lower():
                    return col
        return None


class DriftDetector:
    """
    Detect customers who are "drifting" - their purchase gap is increasing.
    """
    
    def __init__(self, threshold_std: float = 1.0):
        self.threshold_std = threshold_std
        
    def detect_drift(self, df: pd.DataFrame,
                     date_col: str = None,
                     id_col: str = None) -> pd.DataFrame:
        """
        Detect customers whose inter-purchase time is increasing.
        
        Returns customers who are 1+ std deviations above their normal gap.
        """
        # Auto-detect columns
        if date_col is None:
            date_col = [c for c in df.columns if 'date' in c.lower()][0]
        if id_col is None:
            id_col = [c for c in df.columns if 'loyalty' in c.lower() or 'id' in c.lower()][0]
            
        df = df.copy()
        df[date_col] = pd.to_datetime(df[date_col])
        
        analysis_date = df[date_col].max()
        
        # For each customer, calculate purchase gaps over time
        drift_data = []
        
        for customer_id in df[id_col].unique():
            cust_df = df[df[id_col] == customer_id].sort_values(date_col)
            
            if len(cust_df) < 3:
                continue  # Need at least 3 purchases to detect drift
                
            # Calculate gaps between purchases
            gaps = cust_df[date_col].diff().dt.days.dropna()
            
            if len(gaps) < 2:
                continue
                
            avg_gap = gaps.mean()
            std_gap = gaps.std()
            
            # Current gap (days since last purchase)
            last_purchase = cust_df[date_col].max()
            current_gap = (analysis_date - last_purchase).days
            
            # Is current gap above threshold?
            if std_gap > 0:
                z_score = (current_gap - avg_gap) / std_gap
            else:
                z_score = (current_gap - avg_gap) / max(avg_gap, 1)
                
            is_drifting = z_score > self.threshold_std
            
            drift_data.append({
                'customer_id': customer_id,
                'avg_purchase_gap': round(avg_gap, 1),
                'std_gap': round(std_gap, 1),
                'current_gap': current_gap,
                'z_score': round(z_score, 2),
                'is_drifting': is_drifting,
                'drift_severity': 'HIGH' if z_score > 2 else ('MEDIUM' if z_score > 1 else 'LOW')
            })
            
        drift_df = pd.DataFrame(drift_data)
        return drift_df.sort_values('z_score', ascending=False)


class SurvivalPredictor:
    """
    Level 3: Survival Analysis using Cox Proportional Hazards.
    
    Predicts WHEN a customer will churn, not just IF.
    """
    
    def __init__(self):
        self.model = None
        self.fitted = False
        
    def fit(self, df: pd.DataFrame,
            date_col: str = None,
            id_col: str = None,
            point_col: str = None,
            qty_col: str = None) -> Dict:
        """
        Fit Cox model to predict time-to-churn.
        """
        if not LIFELINES_AVAILABLE:
            return {'error': 'lifelines not installed. Run: pip install lifelines'}
        
        # Auto-detect columns
        if date_col is None:
            date_col = [c for c in df.columns if 'date' in c.lower()][0]
        if id_col is None:
            id_col = [c for c in df.columns if 'loyalty' in c.lower() or 'id' in c.lower()][0]
            
        df = df.copy()
        df[date_col] = pd.to_datetime(df[date_col])
        
        analysis_date = df[date_col].max()
        
        # Create survival data per customer
        survival_data = []
        
        for customer_id in df[id_col].unique():
            cust_df = df[df[id_col] == customer_id]
            
            first_purchase = cust_df[date_col].min()
            last_purchase = cust_df[date_col].max()
            
            # Duration = days from first to last purchase
            duration = (last_purchase - first_purchase).days
            
            # Event = 1 if churned (183+ days since last purchase)
            days_since_last = (analysis_date - last_purchase).days
            event = 1 if days_since_last >= 183 else 0
            
            # If not churned, duration = days from first purchase to now
            if event == 0:
                duration = (analysis_date - first_purchase).days
            
            # Features
            frequency = len(cust_df)
            total_points = cust_df[point_col].sum() if point_col and point_col in cust_df.columns else 0
            total_qty = cust_df[qty_col].sum() if qty_col and qty_col in cust_df.columns else 0
            
            # Average gap between purchases
            if frequency > 1:
                avg_gap = cust_df[date_col].sort_values().diff().dt.days.mean()
            else:
                avg_gap = 0
                
            survival_data.append({
                'customer_id': customer_id,
                'duration': max(duration, 1),  # Avoid 0 duration
                'event': event,
                'frequency': frequency,
                'total_points': total_points,
                'total_qty': total_qty,
                'avg_gap': avg_gap
            })
            
        survival_df = pd.DataFrame(survival_data)
        
        # Fit Cox model
        cox = CoxPHFitter()
        features = ['frequency', 'total_points', 'total_qty', 'avg_gap']
        
        # Filter to valid features
        features = [f for f in features if f in survival_df.columns and survival_df[f].sum() > 0]
        
        try:
            cox.fit(survival_df[['duration', 'event'] + features], 
                    duration_col='duration', 
                    event_col='event')
            
            self.model = cox
            self.fitted = True
            self.survival_df = survival_df
            
            return {
                'concordance': round(cox.concordance_index_, 4),
                'hazard_ratios': cox.hazard_ratios_.to_dict(),
                'summary': cox.summary
            }
        except Exception as e:
            return {'error': str(e)}
    
    def predict_survival_probability(self, customer_id: int = None) -> pd.DataFrame:
        """Get survival probability over time for a customer."""
        if not self.fitted:
            raise ValueError("Model not fitted. Run fit() first.")
            
        if customer_id:
            customer_data = self.survival_df[self.survival_df['customer_id'] == customer_id]
            if len(customer_data) == 0:
                raise ValueError(f"Customer {customer_id} not found")
            return self.model.predict_survival_function(customer_data)
        
        return self.model.predict_survival_function(self.survival_df)
    
    def predict_median_survival_time(self) -> pd.DataFrame:
        """Predict median time until churn for each customer."""
        if not self.fitted:
            raise ValueError("Model not fitted. Run fit() first.")
            
        median_times = self.model.predict_median(self.survival_df)
        
        result = self.survival_df[['customer_id']].copy()
        result['median_days_to_churn'] = median_times.values
        result['already_churned'] = self.survival_df['event'].values
        
        return result.sort_values('median_days_to_churn')


class LogisticChurnModel:
    """
    Interpretable churn prediction using Logistic Regression.
    
    Answers: "What factors are driving churn?"
    """
    
    def __init__(self, churn_threshold: int = 183):
        self.churn_threshold = churn_threshold
        self.model = None
        self.scaler = None
        self.feature_names = []
        
    def fit(self, df: pd.DataFrame,
            date_col: str = None,
            id_col: str = None,
            point_col: str = None,
            qty_col: str = None) -> Dict:
        """Fit logistic regression for churn prediction."""
        
        if not SKLEARN_AVAILABLE:
            return {'error': 'scikit-learn not installed'}
        
        # Auto-detect columns
        if date_col is None:
            date_col = [c for c in df.columns if 'date' in c.lower()][0]
        if id_col is None:
            id_col = [c for c in df.columns if 'loyalty' in c.lower() or 'id' in c.lower()][0]
            
        df = df.copy()
        df[date_col] = pd.to_datetime(df[date_col])
        
        analysis_date = df[date_col].max()
        
        # Create features per customer
        features = []
        
        for customer_id in df[id_col].unique():
            cust_df = df[df[id_col] == customer_id]
            
            last_purchase = cust_df[date_col].max()
            first_purchase = cust_df[date_col].min()
            recency = (analysis_date - last_purchase).days
            frequency = len(cust_df)
            lifetime = (last_purchase - first_purchase).days
            
            total_points = cust_df[point_col].sum() if point_col and point_col in cust_df.columns else 0
            total_qty = cust_df[qty_col].sum() if qty_col and qty_col in cust_df.columns else 0
            
            # Average gap
            if frequency > 1:
                avg_gap = cust_df[date_col].sort_values().diff().dt.days.mean()
            else:
                avg_gap = 0
                
            # Target
            is_churned = 1 if recency >= self.churn_threshold else 0
            
            features.append({
                'customer_id': customer_id,
                'recency': recency,
                'frequency': frequency,
                'lifetime': lifetime,
                'total_points': total_points,
                'total_qty': total_qty,
                'avg_gap': avg_gap,
                'is_churned': is_churned
            })
            
        feature_df = pd.DataFrame(features)
        
        # Prepare features
        feature_cols = ['recency', 'frequency', 'lifetime', 'total_points', 'total_qty', 'avg_gap']
        X = feature_df[feature_cols]
        y = feature_df['is_churned']
        
        # Scale
        self.scaler = StandardScaler()
        X_scaled = self.scaler.fit_transform(X)
        
        # Split
        X_train, X_test, y_train, y_test = train_test_split(X_scaled, y, test_size=0.2, random_state=42)
        
        # Fit
        self.model = LogisticRegression(max_iter=1000)
        self.model.fit(X_train, y_train)
        
        self.feature_names = feature_cols
        
        # Results
        accuracy = self.model.score(X_test, y_test)
        
        # Coefficients interpretation
        coef_df = pd.DataFrame({
            'feature': feature_cols,
            'coefficient': self.model.coef_[0],
            'odds_ratio': np.exp(self.model.coef_[0])
        }).sort_values('coefficient', key=abs, ascending=False)
        
        return {
            'accuracy': round(accuracy, 4),
            'coefficients': coef_df.to_dict('records'),
            'interpretation': self._interpret_coefficients(coef_df)
        }
    
    def _interpret_coefficients(self, coef_df: pd.DataFrame) -> List[str]:
        """Generate human-readable coefficient interpretations."""
        interpretations = []
        
        for _, row in coef_df.iterrows():
            feat = row['feature']
            coef = row['coefficient']
            odds = row['odds_ratio']
            
            if coef > 0:
                interpretations.append(
                    f"↑ {feat}: Increases churn risk (odds ratio: {odds:.2f})"
                )
            else:
                interpretations.append(
                    f"↓ {feat}: Decreases churn risk (odds ratio: {odds:.2f})"
                )
                
        return interpretations


class MultiLevelChurnSystem:
    """
    Complete multi-level churn prediction system.
    
    Combines:
    - Level 1: RFM Analysis
    - Level 2: ML Models (Logistic, XGBoost, Panel)
    - Level 3: Survival Analysis
    """
    
    def __init__(self, churn_threshold: int = 183):
        self.churn_threshold = churn_threshold
        self.rfm_analyzer = RFMAnalyzer(churn_threshold)
        self.drift_detector = DriftDetector()
        self.survival_predictor = SurvivalPredictor()
        self.logistic_model = LogisticChurnModel(churn_threshold)
        
        self.results = {}
        
    def run(self, df: pd.DataFrame) -> Dict:
        """Run complete multi-level analysis."""
        
        print("="*80)
        print("MULTI-LEVEL CHURN ANALYSIS")
        print("="*80)
        
        # Level 1: RFM
        print("\n[Level 1] RFM Analysis...")
        try:
            rfm_df = self.rfm_analyzer.calculate_rfm(df)
            churning_champions = self.rfm_analyzer.get_churning_champions()
            
            print(f"  ✓ {len(rfm_df)} customers analyzed")
            print(f"  ✓ {len(churning_champions)} CHURNING CHAMPIONS (high-value at-risk)")
            
            self.results['rfm'] = rfm_df
            self.results['churning_champions'] = churning_champions
        except Exception as e:
            print(f"  ✗ Error: {e}")
            
        # Drift Detection
        print("\n[Drift] Inter-Purchase Gap Analysis...")
        try:
            drift_df = self.drift_detector.detect_drift(df)
            drifting = drift_df[drift_df['is_drifting']]
            
            print(f"  ✓ {len(drifting)} customers DRIFTING (gap increasing)")
            
            self.results['drift'] = drift_df
        except Exception as e:
            print(f"  ✗ Error: {e}")
            
        # Level 2: Logistic Regression
        print("\n[Level 2] Logistic Regression...")
        try:
            logistic_results = self.logistic_model.fit(df)
            
            if 'error' not in logistic_results:
                print(f"  ✓ Accuracy: {logistic_results['accuracy']:.1%}")
                print("  ✓ Top drivers of churn:")
                for interp in logistic_results['interpretation'][:3]:
                    print(f"    {interp}")
                    
            self.results['logistic'] = logistic_results
        except Exception as e:
            print(f"  ✗ Error: {e}")
            
        # Level 3: Survival Analysis
        print("\n[Level 3] Survival Analysis...")
        try:
            if LIFELINES_AVAILABLE:
                survival_results = self.survival_predictor.fit(df)
                
                if 'error' not in survival_results:
                    print(f"  ✓ Concordance Index: {survival_results['concordance']:.3f}")
                    
                    # Predict median survival
                    median_survival = self.survival_predictor.predict_median_survival_time()
                    self.results['median_survival'] = median_survival
                    
                self.results['survival'] = survival_results
            else:
                print("  ✗ lifelines not installed. Run: pip install lifelines")
        except Exception as e:
            print(f"  ✗ Error: {e}")
            
        print("\n" + "="*80)
        print("ANALYSIS COMPLETE")
        print("="*80)
        
        return self.results
    
    def get_priority_list(self) -> pd.DataFrame:
        """Get combined priority list of customers to contact."""
        
        if 'rfm' not in self.results:
            raise ValueError("Run analysis first")
            
        priority_df = self.results['rfm'][['customer_id', 'segment', 'action_priority', 
                                           'recency_days', 'frequency', 'RFM_score']].copy()
        
        # Add drift status
        if 'drift' in self.results:
            drift_map = self.results['drift'].set_index('customer_id')['is_drifting'].to_dict()
            priority_df['is_drifting'] = priority_df['customer_id'].map(drift_map).fillna(False)
        
        # Add seasonal predictions
        if 'seasonal_predictions' in self.results:
            seasonal_map = self.results['seasonal_predictions'].set_index('customer_id')[['avg_3month_prob', 'risk_level', 'action']].to_dict('index')
            
            priority_df['avg_3month_prob'] = priority_df['customer_id'].map(lambda x: seasonal_map.get(x, {}).get('avg_3month_prob', 0.0))
            priority_df['risk_level'] = priority_df['customer_id'].map(lambda x: seasonal_map.get(x, {}).get('risk_level', 'LOW'))
            priority_df['recommended_action'] = priority_df['customer_id'].map(lambda x: seasonal_map.get(x, {}).get('action', 'Monitor'))
            
        return priority_df.sort_values(['action_priority', 'recency_days'], 
                                       ascending=[True, False])
    
    def get_monthly_summary(self, forecast_df: pd.DataFrame) -> pd.DataFrame:
        """Get summary of expected churn by month."""
        
        summary = []
        
        # Dynamically get month columns from forecast_df
        prob_cols = [col for col in forecast_df.columns if col.endswith('_prob')]
        
        for prob_col in prob_cols:
            month_name = prob_col.replace('_prob', '') # e.g., 'Jan' from 'Jan_prob'
            
            high_risk = len(forecast_df[forecast_df[prob_col] >= 0.7])
            medium_risk = len(forecast_df[(forecast_df[prob_col] >= 0.4) & (forecast_df[prob_col] < 0.7)])
            low_risk = len(forecast_df[forecast_df[prob_col] < 0.4])
            avg_prob = forecast_df[prob_col].mean()
            
            summary.append({
                'month': month_name,
                'high_risk_count': high_risk,
                'medium_risk_count': medium_risk,
                'low_risk_count': low_risk,
                'avg_churn_prob': round(avg_prob, 3)
            })
        
        return pd.DataFrame(summary)


class SeasonalChurnPredictor:
    """
    3-Month Churn Prediction with Seasonality Adjustment.
    """
    
    DEFAULT_SEASONALITY = {
        1: 0.80, 2: 0.75, 3: 0.70, 4: 0.62, 5: 0.93, 6: 0.89,
        7: 1.08, 8: 1.32, 9: 1.27, 10: 1.83, 11: 0.87, 12: 0.18
    }
    
    def __init__(self, seasonality_file: str = None):
        self.seasonality = self.DEFAULT_SEASONALITY.copy()
        if seasonality_file:
            try:
                season_df = pd.read_csv(seasonality_file)
                for _, row in season_df.iterrows():
                    self.seasonality[int(row['month'])] = row['seasonality_index']
            except:
                pass
    
    def predict_3months(self, rfm_df: pd.DataFrame) -> pd.DataFrame:
        """Predict churn probability for next 3 months."""
        from datetime import datetime
        
        today = datetime.now()
        next_months = [((today.month + i - 1) % 12) + 1 for i in range(1, 4)]
        month_names = {1:'Jan', 2:'Feb', 3:'Mar', 4:'Apr', 5:'May', 6:'Jun',
                       7:'Jul', 8:'Aug', 9:'Sep', 10:'Oct', 11:'Nov', 12:'Dec'}
        
        predictions = []
        for _, c in rfm_df.iterrows():
            recency = c['recency_days']
            freq = c.get('frequency', 1)
            rfm = c.get('RFM_score', 9)
            
            # Base probability from recency
            if recency >= 183:
                base = min(0.95, 0.5 + (recency - 183) / 365)
            elif recency >= 120:
                base = 0.3 + (recency - 120) / 210
            elif recency >= 60:
                base = 0.1 + (recency - 60) / 300
            else:
                base = recency / 600
            
            # Frequency adjustment
            if freq >= 10: base *= 0.8
            elif freq >= 5: base *= 0.9
            
            # RFM adjustment
            if rfm >= 12: base *= 0.7
            elif rfm >= 9: base *= 0.85
            
            # Calculate per month
            probs = []
            for i, m in enumerate(next_months):
                future_days = (i + 1) * 30
                season = self.seasonality.get(m, 1.0)
                adj = 1.0 / season if season > 1.0 else 1.0
                prob = min(0.99, max(0.01, base * (1 + future_days/365) * adj))
                probs.append(round(prob, 3))
            
            avg = sum(probs) / 3
            risk = 'HIGH' if avg >= 0.7 else ('MEDIUM' if avg >= 0.4 else 'LOW')
            action = 'Call now' if risk == 'HIGH' else ('Email + discount' if risk == 'MEDIUM' else 'Monitor')
            
            predictions.append({
                'customer_id': c['customer_id'],
                'current_recency': recency,
                f'{month_names[next_months[0]]}_prob': probs[0],
                f'{month_names[next_months[1]]}_prob': probs[1],
                f'{month_names[next_months[2]]}_prob': probs[2],
                'avg_3month_prob': round(avg, 3),
                'risk_level': risk,
                'action': action,
                'frequency': freq
            })
        
        return pd.DataFrame(predictions).sort_values('avg_3month_prob', ascending=False)


class GeographicChannelAnalyzer:
    """
    Analyzes the impact of State, Retailer, and Distributor on churn.
    Identifies high-risk geographic/channel combinations.
    """
    
    def __init__(self, churn_threshold: int = 183):
        self.churn_threshold = churn_threshold
        self.state_analysis = None
        self.retailer_analysis = None
        self.distributor_analysis = None
        self.insights = []
    
    def analyze(self, df: pd.DataFrame, rfm_df: pd.DataFrame = None) -> Dict:
        """Run geographic and channel analysis."""
        
        # Auto-detect columns
        id_col = self._find_col(df, ['membership', 'loyalty', 'id', 'customer'])
        date_col = self._find_col(df, ['trxn_date', 'date', 'trxn'])
        state_col = self._find_col(df, ['state'])
        retailer_col = self._find_col(df, ['retailer'])
        distributor_col = self._find_col(df, ['distributor'])
        
        df = df.copy()
        df[date_col] = pd.to_datetime(df[date_col])
        analysis_date = df[date_col].max()
        
        # Build customer-level data with geographic info
        customer_data = df.groupby(id_col).agg({
            date_col: 'max',
            state_col: 'first' if state_col else lambda x: 'Unknown',
            retailer_col: 'first' if retailer_col else lambda x: 'Unknown',
            distributor_col: 'first' if distributor_col else lambda x: 0,
        }).reset_index()
        
        customer_data.columns = ['customer_id', 'last_purchase', 'state', 'retailer', 'distributor']
        customer_data['recency'] = (analysis_date - customer_data['last_purchase']).dt.days
        customer_data['is_churned'] = customer_data['recency'] >= self.churn_threshold
        
        overall_churn = customer_data['is_churned'].mean()
        self.insights = []
        
        # 1. State Analysis
        if state_col:
            self.state_analysis = self._analyze_dimension(customer_data, 'state', overall_churn)
        
        # 2. Retailer Analysis
        if retailer_col:
            self.retailer_analysis = self._analyze_dimension(customer_data, 'retailer', overall_churn)
        
        # 3. Distributor Analysis
        if distributor_col:
            self.distributor_analysis = self._analyze_dimension(customer_data, 'distributor', overall_churn)
        
        # Generate insights
        self._generate_insights(overall_churn)
        
        return {
            'state_analysis': self.state_analysis,
            'retailer_analysis': self.retailer_analysis,
            'distributor_analysis': self.distributor_analysis,
            'insights': self.insights,
            'overall_churn_rate': overall_churn
        }
    
    def _find_col(self, df: pd.DataFrame, keywords: List[str]) -> str:
        for col in df.columns:
            for kw in keywords:
                if kw.lower() in col.lower():
                    return col
        return None
    
    def _analyze_dimension(self, data: pd.DataFrame, dimension: str, overall_churn: float) -> pd.DataFrame:
        """Analyze churn by a single dimension."""
        
        analysis = data.groupby(dimension).agg({
            'customer_id': 'count',
            'is_churned': ['sum', 'mean']
        }).reset_index()
        
        analysis.columns = [dimension, 'customers', 'churned', 'churn_rate']
        analysis['churn_rate_pct'] = analysis['churn_rate'] * 100
        analysis['vs_avg'] = (analysis['churn_rate'] - overall_churn) * 100
        analysis['risk_flag'] = analysis['vs_avg'].apply(
            lambda x: 'HIGH_RISK' if x > 15 else ('LOW_RISK' if x < -15 else 'NORMAL')
        )
        
        return analysis.sort_values('churn_rate_pct', ascending=False)
    
    def _generate_insights(self, overall_churn: float):
        """Generate actionable insights from the analysis."""
        
        overall_pct = overall_churn * 100
        
        # State insights
        if self.state_analysis is not None:
            high_risk_states = self.state_analysis[
                (self.state_analysis['risk_flag'] == 'HIGH_RISK') & 
                (self.state_analysis['customers'] >= 10)
            ]
            if len(high_risk_states) > 0:
                states = ', '.join(high_risk_states.head(3)[self.state_analysis.columns[0]].tolist())
                self.insights.append({
                    'type': 'STATE',
                    'severity': 'HIGH',
                    'message': f"High-churn states detected: {states}",
                    'action': "Investigate regional service issues or competition"
                })
        
        # Retailer insights
        if self.retailer_analysis is not None:
            high_risk = self.retailer_analysis[
                (self.retailer_analysis['risk_flag'] == 'HIGH_RISK') & 
                (self.retailer_analysis['customers'] >= 10)
            ]
            if len(high_risk) > 0:
                self.insights.append({
                    'type': 'RETAILER',
                    'severity': 'HIGH',
                    'message': f"{len(high_risk)} retailers have churn rate >{overall_pct+15:.0f}%",
                    'action': "Review retailer performance and customer service quality"
                })
            
            low_risk = self.retailer_analysis[
                (self.retailer_analysis['risk_flag'] == 'LOW_RISK') & 
                (self.retailer_analysis['customers'] >= 10)
            ]
            if len(low_risk) > 0:
                self.insights.append({
                    'type': 'RETAILER',
                    'severity': 'INFO',
                    'message': f"{len(low_risk)} retailers have excellent retention (<{overall_pct-15:.0f}%)",
                    'action': "Study and replicate their best practices"
                })
        
        # Distributor insights
        if self.distributor_analysis is not None:
            high_risk = self.distributor_analysis[
                (self.distributor_analysis['risk_flag'] == 'HIGH_RISK') & 
                (self.distributor_analysis['customers'] >= 10)
            ]
            if len(high_risk) > 0:
                self.insights.append({
                    'type': 'DISTRIBUTOR',
                    'severity': 'HIGH',
                    'message': f"{len(high_risk)} distributors have high churn rates",
                    'action': "Audit distributor service levels and supply chain issues"
                })
    
    def get_high_risk_combinations(self, df: pd.DataFrame) -> pd.DataFrame:
        """Find state-distributor combinations with highest churn."""
        
        id_col = self._find_col(df, ['membership', 'loyalty', 'id', 'customer'])
        date_col = self._find_col(df, ['trxn_date', 'date', 'trxn'])
        state_col = self._find_col(df, ['state'])
        distributor_col = self._find_col(df, ['distributor'])
        
        if not all([id_col, date_col, state_col, distributor_col]):
            return pd.DataFrame()
        
        df = df.copy()
        df[date_col] = pd.to_datetime(df[date_col])
        analysis_date = df[date_col].max()
        
        customer_data = df.groupby(id_col).agg({
            date_col: 'max',
            state_col: 'first',
            distributor_col: 'first',
        }).reset_index()
        
        customer_data.columns = ['customer_id', 'last_purchase', 'state', 'distributor']
        customer_data['recency'] = (analysis_date - customer_data['last_purchase']).dt.days
        customer_data['is_churned'] = customer_data['recency'] >= self.churn_threshold
        
        combo = customer_data.groupby(['state', 'distributor']).agg({
            'customer_id': 'count',
            'is_churned': 'mean'
        }).reset_index()
        
        combo.columns = ['state', 'distributor', 'customers', 'churn_rate']
        combo['churn_rate_pct'] = combo['churn_rate'] * 100
        combo = combo[combo['customers'] >= 5]
        
        return combo.sort_values('churn_rate_pct', ascending=False)


class StateAdjustedChurnAnalyzer:
    """
    Analyzes churn with state-specific thresholds based on regional buying patterns.
    Compares flat threshold vs state-adjusted approach.
    """
    
    def __init__(self, flat_threshold: int = 183, multiplier: float = 3.0):
        self.flat_threshold = flat_threshold
        self.multiplier = multiplier  # Threshold = median_gap * multiplier
        self.state_thresholds = {}
        self.comparison_df = None
    
    def analyze(self, df: pd.DataFrame) -> Dict:
        """Run state-adjusted churn analysis."""
        
        # Auto-detect columns
        id_col = self._find_col(df, ['membership', 'loyalty', 'id', 'customer'])
        date_col = self._find_col(df, ['trxn_date', 'date', 'trxn'])
        state_col = self._find_col(df, ['state'])
        
        df = df.copy()
        df[date_col] = pd.to_datetime(df[date_col])
        analysis_date = df[date_col].max()
        
        # Build customer data
        customer_data = df.groupby(id_col).agg({
            date_col: ['min', 'max', 'count'],
            state_col: 'first' if state_col else lambda x: 'Unknown'
        }).reset_index()
        
        customer_data.columns = ['customer_id', 'first_purchase', 'last_purchase', 'frequency', 'state']
        customer_data['recency'] = (analysis_date - customer_data['last_purchase']).dt.days
        customer_data['lifetime'] = (customer_data['last_purchase'] - customer_data['first_purchase']).dt.days
        
        # Calculate average gap per customer
        customer_data['avg_gap'] = customer_data.apply(
            lambda r: r['lifetime'] / (r['frequency'] - 1) if r['frequency'] > 1 else 60,
            axis=1
        )
        
        # Calculate state patterns
        state_patterns = customer_data.groupby('state').agg({
            'avg_gap': 'median',
            'frequency': 'median',
            'customer_id': 'count'
        }).reset_index()
        state_patterns.columns = ['state', 'median_gap', 'median_freq', 'customers']
        
        # State-specific threshold: multiplier * median gap, clamped 90-365
        state_patterns['adjusted_threshold'] = state_patterns['median_gap'].apply(
            lambda x: int(min(max(x * self.multiplier, 90), 365))
        )
        
        self.state_thresholds = state_patterns.set_index('state')['adjusted_threshold'].to_dict()
        
        # Apply both methods
        customer_data['churned_flat'] = customer_data['recency'] >= self.flat_threshold
        customer_data['state_threshold'] = customer_data['state'].map(self.state_thresholds)
        customer_data['churned_adjusted'] = customer_data['recency'] >= customer_data['state_threshold']
        
        # Calculate metrics
        total = len(customer_data)
        flat_churned = customer_data['churned_flat'].sum()
        adj_churned = customer_data['churned_adjusted'].sum()
        
        # Comparison by state
        comparison = customer_data.groupby('state').agg({
            'customer_id': 'count',
            'churned_flat': 'mean',
            'churned_adjusted': 'mean',
            'state_threshold': 'first'
        }).reset_index()
        comparison.columns = ['state', 'customers', 'flat_rate', 'adjusted_rate', 'threshold']
        comparison['flat_pct'] = comparison['flat_rate'] * 100
        comparison['adjusted_pct'] = comparison['adjusted_rate'] * 100
        comparison['difference'] = comparison['adjusted_pct'] - comparison['flat_pct']
        
        self.comparison_df = comparison
        
        # Reclassified customers
        reclassified = customer_data[customer_data['churned_flat'] != customer_data['churned_adjusted']]
        
        return {
            'customer_data': customer_data,
            'state_patterns': state_patterns,
            'comparison': comparison,
            'reclassified': reclassified,
            'summary': {
                'total_customers': total,
                'flat_churned': int(flat_churned),
                'flat_rate': flat_churned / total * 100,
                'adjusted_churned': int(adj_churned),
                'adjusted_rate': adj_churned / total * 100,
                'difference_customers': int(adj_churned - flat_churned),
                'difference_rate': (adj_churned - flat_churned) / total * 100,
                'reclassified_count': len(reclassified),
                'now_active': len(reclassified[~reclassified['churned_adjusted']]),
                'now_churned': len(reclassified[reclassified['churned_adjusted']])
            }
        }
    
    def _find_col(self, df: pd.DataFrame, keywords: List[str]) -> str:
        for col in df.columns:
            for kw in keywords:
                if kw.lower() in col.lower():
                    return col
        return None


class MultiFactorChurnAnalyzer:
    """
    Multi-factor churn analysis considering State, Retailer, and Customer-Retailer relationship.
    """
    
    def __init__(self, flat_threshold: int = 183, multiplier: float = 3.0):
        self.flat_threshold = flat_threshold
        self.multiplier = multiplier
    
    def analyze(self, df: pd.DataFrame) -> Dict:
        """Run multi-factor churn analysis."""
        
        id_col = self._find_col(df, ['membership', 'loyalty', 'id', 'customer'])
        date_col = self._find_col(df, ['trxn_date', 'date', 'trxn'])
        state_col = self._find_col(df, ['state'])
        retailer_col = self._find_col(df, ['retailer'])
        
        df = df.copy()
        df[date_col] = pd.to_datetime(df[date_col])
        analysis_date = df[date_col].max()
        
        # Build customer data with primary retailer
        cust_agg = {
            date_col: ['min', 'max', 'count'],
        }
        if state_col:
            cust_agg[state_col] = 'first'
        if retailer_col:
            cust_agg[retailer_col] = lambda x: x.mode()[0] if len(x) > 0 else 'Unknown'
        
        customer_data = df.groupby(id_col).agg(cust_agg).reset_index()
        
        # Flatten columns
        cols = ['customer_id', 'first_purchase', 'last_purchase', 'frequency']
        if state_col:
            cols.append('state')
        if retailer_col:
            cols.append('primary_retailer')
        customer_data.columns = cols
        
        customer_data['recency'] = (analysis_date - customer_data['last_purchase']).dt.days
        customer_data['lifetime'] = (customer_data['last_purchase'] - customer_data['first_purchase']).dt.days
        customer_data['avg_gap'] = customer_data.apply(
            lambda r: r['lifetime'] / (r['frequency'] - 1) if r['frequency'] > 1 else 60, axis=1
        )
        
        # Calculate retailer loyalty
        if retailer_col:
            cust_ret = df.groupby([id_col, retailer_col]).size().reset_index(name='txn_count')
            primary_txns = cust_ret.loc[cust_ret.groupby(id_col)['txn_count'].idxmax()][[id_col, 'txn_count']]
            primary_txns.columns = ['customer_id', 'primary_retailer_txns']
            customer_data = customer_data.merge(primary_txns, on='customer_id', how='left')
            customer_data['retailer_loyalty'] = (customer_data['primary_retailer_txns'] / 
                                                  customer_data['frequency']).fillna(0.5)
        else:
            customer_data['retailer_loyalty'] = 0.5
        
        # State patterns
        state_patterns = None
        if state_col and 'state' in customer_data.columns:
            state_patterns = customer_data.groupby('state').agg({
                'avg_gap': 'median',
                'customer_id': 'count'
            }).reset_index()
            state_patterns.columns = ['state', 'median_gap', 'customers']
            state_patterns['threshold'] = state_patterns['median_gap'].apply(
                lambda x: int(min(max(x * self.multiplier, 90), 365))
            )
            state_thresh = state_patterns.set_index('state')['threshold'].to_dict()
            customer_data['state_threshold'] = customer_data['state'].map(state_thresh).fillna(self.flat_threshold)
        else:
            customer_data['state_threshold'] = self.flat_threshold
        
        # Retailer patterns
        retailer_patterns = None
        if retailer_col and 'primary_retailer' in customer_data.columns:
            retailer_patterns = customer_data.groupby('primary_retailer').agg({
                'avg_gap': 'median',
                'customer_id': 'count'
            }).reset_index()
            retailer_patterns.columns = ['retailer', 'median_gap', 'customers']
            retailer_patterns = retailer_patterns[retailer_patterns['customers'] >= 5]
            retailer_patterns['threshold'] = retailer_patterns['median_gap'].apply(
                lambda x: int(min(max(x * self.multiplier, 90), 365))
            )
            ret_thresh = retailer_patterns.set_index('retailer')['threshold'].to_dict()
            customer_data['retailer_threshold'] = customer_data['primary_retailer'].map(ret_thresh).fillna(self.flat_threshold)
        else:
            customer_data['retailer_threshold'] = self.flat_threshold
        
        # Combined threshold
        customer_data['combined_threshold'] = (
            customer_data['retailer_loyalty'] * customer_data['retailer_threshold'] +
            (1 - customer_data['retailer_loyalty']) * customer_data['state_threshold']
        ).astype(int).clip(90, 365)
        
        # Calculate churn
        customer_data['churned_flat'] = customer_data['recency'] >= self.flat_threshold
        customer_data['churned_state'] = customer_data['recency'] >= customer_data['state_threshold']
        customer_data['churned_retailer'] = customer_data['recency'] >= customer_data['retailer_threshold']
        customer_data['churned_combined'] = customer_data['recency'] >= customer_data['combined_threshold']
        
        total = len(customer_data)
        
        return {
            'customer_data': customer_data,
            'state_patterns': state_patterns,
            'retailer_patterns': retailer_patterns,
            'summary': {
                'total': total,
                'flat_churned': int(customer_data['churned_flat'].sum()),
                'flat_rate': customer_data['churned_flat'].mean() * 100,
                'state_churned': int(customer_data['churned_state'].sum()),
                'state_rate': customer_data['churned_state'].mean() * 100,
                'retailer_churned': int(customer_data['churned_retailer'].sum()),
                'retailer_rate': customer_data['churned_retailer'].mean() * 100,
                'combined_churned': int(customer_data['churned_combined'].sum()),
                'combined_rate': customer_data['churned_combined'].mean() * 100,
            }
        }
    
    def _find_col(self, df: pd.DataFrame, keywords: List[str]) -> str:
        for col in df.columns:
            for kw in keywords:
                if kw.lower() in col.lower():
                    return col
        return None


