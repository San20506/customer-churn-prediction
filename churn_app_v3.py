    def _run_analysis(self):
        """Run the multi-level churn analysis."""
        
        def analyze():
            try:
                self.status_label.configure(text="Analyzing...")
                self.analyze_btn.configure(state="disabled")
                
                # Load data
                sheet = self.sheet_var.get()
                self.df = pd.read_excel(self.file_path, sheet_name=sheet)
                
                # Run multi-level analysis
                threshold = self.threshold_var.get()
                system = MultiLevelChurnSystem(churn_threshold=threshold)
                self.analysis_results = system.run(self.df)
                
                # Get priority list
                self.priority_list = system.get_priority_list()
                
                # Get recently churned customers
                self.recently_churned = system.rfm_analyzer.get_recently_churned()
                
                # Get timeline summary
                self.timeline_summary = system.rfm_analyzer.get_churn_timeline_summary()
                
                # Generate 3-month seasonal forecast
                seasonal_predictor = SeasonalChurnPredictor(
                    seasonality_file='seasonality_index.csv'
                )
                self.forecast_3month = seasonal_predictor.predict_3months(
                    self.analysis_results['rfm']
                )
                
                # Run geographic/channel analysis
                geo_analyzer = GeographicChannelAnalyzer(churn_threshold=threshold)
                self.geo_results = geo_analyzer.analyze(self.df)
                
                # Run multi-factor churn analysis (State + Retailer + Loyalty)
                multi_analyzer = MultiFactorChurnAnalyzer(flat_threshold=threshold)
                self.multi_factor_results = multi_analyzer.analyze(self.df)
                
                # Run ML-based prediction model
                ml_model = MultiFactorPredictionModel(churn_threshold=threshold)
                self.ml_results = ml_model.fit_and_predict(self.df)
                
                # Update UI
                self.after(0, self._update_dashboard)
                self.after(0, self._update_analytics_tab)
                self.after(0, self._update_ml_tab)
                self.after(0, self._update_rfm_tab)
                self.after(0, self._update_priority_tab)
                self.after(0, self._update_forecast_tab)
                self.after(0, self._update_geo_tab)
                self.after(0, self._update_recently_churned_tab)
                self.after(0, self._update_drift_tab)
                self.after(0, self._update_survival_tab)
                
                self.status_label.configure(text="Analysis complete!")
                self.analyze_btn.configure(state="normal")
                self.export_btn.configure(state="normal")
                
            except Exception as e:
                self.status_label.configure(text=f"Error: {e}")
                self.analyze_btn.configure(state="normal")
                
        threading.Thread(target=analyze, daemon=True).start()
        
